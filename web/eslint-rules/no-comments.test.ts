import { Linter } from 'eslint';
import { describe, expect, test } from 'vitest';
import noComments from './no-comments.js';

const linter = new Linter();

function lint(code: string, filename = 'src/sample.ts') {
  return linter.verify(
    code,
    [
      {
        files: ['**/*.ts'],
        plugins: { local: { rules: { 'no-comments': noComments } } },
        rules: { 'local/no-comments': 'error' },
      },
    ],
    filename,
  );
}

describe('local/no-comments', () => {
  test('reports a line comment where it is', () => {
    const messages = lint('const a = 1;\n// the answer\nexport { a };\n');
    expect(messages.map((m) => [m.ruleId, m.line])).toEqual([['local/no-comments', 2]]);
  });

  test('reports a block comment', () => {
    const messages = lint('/* the answer */ export const a = 1;\n');
    expect(messages.map((m) => [m.ruleId, m.line])).toEqual([['local/no-comments', 1]]);
  });

  test('reports every comment', () => {
    const messages = lint('// one\nexport const a = 1; /* two */\n');
    expect(messages).toHaveLength(2);
  });

  test('accepts code without comments, even with slashes in strings', () => {
    expect(lint("export const url = 'http://localhost:7878/api';\n")).toEqual([]);
  });

  test('accepts the marker header of the generated types file only', () => {
    const header = '// Code generated by go run ./cmd/gentypes; DO NOT EDIT.\nexport const a = 1;\n';
    expect(lint(header, 'src/api/types.gen.ts')).toEqual([]);
    expect(lint(header, 'src/api/types.ts')).toHaveLength(1);
  });
});
