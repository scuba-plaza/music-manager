type IntKeys struct {
	ByNumber map[int]string `json:"byNumber"`
}

func TestAMapWithKeysThatAreNotStringsIsAnError(t *testing.T) {
	_, err := Generate(IntKeys{})
	if err == nil || !strings.Contains(err.Error(), "IntKeys.ByNumber") {
		t.Fatalf("want an error naming IntKeys.ByNumber, got %v", err)
	}
}

type Base struct {
	ID   string `json:"id"`
	Kind string `json:"kind"`
}

type Extra struct {
	Note string `json:"note,omitempty"`
}

type Tagged struct {
	Label string `json:"label"`
}

type Change struct {
	Base
	*Extra
	Tagged  `json:"tagged"`
	Kind    int    `json:"kind"`
	History string `json:"history"`
}

func TestEmbeddedStructsAreFlattened(t *testing.T) {
	check(t, generate(t, Change{}), generated+`
export interface Change {
  id: string;
  note?: string;
  tagged: Tagged;
  kind: number;
  history: string;
}

export interface Tagged {
  label: string;
}
`)
	raw, err := json.Marshal(Change{Extra: &Extra{Note: "n"}})
	if err != nil {
		t.Fatal(err)
	}
	if want := `{"id":"","note":"n","tagged":{"label":""},"kind":0,"history":""}`; string(raw) != want {
		t.Errorf("encoding/json writes %s, want %s", raw, want)
	}
}

type Loose struct {
	Data    any             `json:"data,omitempty"`
	Old     interface{}     `json:"old"`
	Raw     json.RawMessage `json:"raw"`
	Fault   error           `json:"fault"`
	Company string          `json:"company"`
	Anyway  []any           `json:"anyway"`
}

func TestUnknownReplacesAny(t *testing.T) {
	out := generate(t, Loose{})
	if regexp.MustCompile(`\bany\b`).MatchString(out) {
		t.Errorf("the output says any:\n%s", out)
	}
	check(t, out, generated+`
export interface Loose {
  data?: unknown;
  old: unknown;
  raw: unknown;
  fault: unknown;
  company: string;
  anyway: unknown[] | null;
}
`)
}

type Zebra struct {
	A Mango `json:"a"`
}

type Mango struct {
	B Apple `json:"b"`
}

type Apple struct {
	C string `json:"c"`
}

type Nothing struct{}

func TestOutputIsDeterministic(t *testing.T) {
	first := generate(t, Zebra{}, Nothing{}, Apple{})
	for range 20 {
		if again := generate(t, Nothing{}, Apple{}, Zebra{}); again != first {
			t.Fatalf("two runs differ:\n%s\n---\n%s", first, again)
		}
	}
	check(t, first, generated+`
export interface Apple {
  c: string;
}

export interface Mango {
  b: Apple;
}

export type Nothing = Record<string, never>;

export interface Zebra {
  a: Mango;
}
`)
}

type Callback struct {
	Name   string     `json:"name"`
	OnDone func()     `json:"onDone"`
	Ticks  chan int   `json:"ticks"`
	Inner  []Callback `json:"inner"`
}

type Ticker struct {
	Ticks chan int `json:"ticks"`
}

func TestAFunctionFieldIsAnError(t *testing.T) {
	_, err := Generate(Callback{})
	if err == nil || !strings.Contains(err.Error(), "Callback.OnDone") {
		t.Fatalf("want an error naming Callback.OnDone, got %v", err)
	}
	_, err = Generate(Ticker{})
	if err == nil || !strings.Contains(err.Error(), "Ticker.Ticks") {
		t.Fatalf("want an error naming Ticker.Ticks, got %v", err)
	}
}

type Stamp struct{ n int }

func (s Stamp) MarshalJSON() ([]byte, error) { return json.Marshal(s.n) }

type Stamped struct {
	At Stamp `json:"at"`
}

func TestATypeThatMarshalsItselfIsAnError(t *testing.T) {
	_, err := Generate(Stamped{})
	if err == nil || !strings.Contains(err.Error(), "Stamped.At") {
		t.Fatalf("want an error naming Stamped.At, got %v", err)
	}
}

func TestARootThatIsNotAStructIsAnError(t *testing.T) {
	if _, err := Generate("stamp"); err == nil {
		t.Fatal("want an error for a string root")
	}
}

func TestTwoTypesOfOneNameAreAnError(t *testing.T) {
	type Song struct {
		Name string `json:"name"`
	}
	type Pair struct {
		Local Song `json:"local"`
	}
	_, err := Generate(Album{}, Pair{})
	if err == nil || !strings.Contains(err.Error(), "Song") {
		t.Fatalf("want an error naming Song, got %v", err)
	}
}

