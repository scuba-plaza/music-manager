package tsgen

import (
	"cmp"
	"encoding"
	"encoding/json"
	"fmt"
	"reflect"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"time"
)

const header = "// Code generated by go run ./cmd/gentypes; DO NOT EDIT.\n"

var (
	timeType          = reflect.TypeFor[time.Time]()
	rawMessageType    = reflect.TypeFor[json.RawMessage]()
	jsonMarshalerType = reflect.TypeFor[json.Marshaler]()
	textMarshalerType = reflect.TypeFor[encoding.TextMarshaler]()
	identifier        = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)
)

type generator struct {
	named map[string]reflect.Type
	decls map[string]string
	queue []reflect.Type
}

type field struct {
	name     string
	index    []int
	tagged   bool
	typ      reflect.Type
	owner    reflect.Type
	goName   string
	optional bool
	quoted   bool
}

func Generate(roots ...any) (string, error) {
	g := &generator{named: map[string]reflect.Type{}, decls: map[string]string{}}
	for _, root := range roots {
		t := reflect.TypeOf(root)
		for t != nil && t.Kind() == reflect.Pointer {
			t = t.Elem()
		}
		if t == nil || t.Kind() != reflect.Struct {
			return "", fmt.Errorf("a root must be a struct, not %v", t)
		}
		if err := g.declare(t); err != nil {
			return "", err
		}
	}
	for len(g.queue) > 0 {
		t := g.queue[0]
		g.queue = g.queue[1:]
		decl, err := g.declaration(t)
		if err != nil {
			return "", err
		}
		g.decls[t.Name()] = decl
	}
	names := make([]string, 0, len(g.decls))
	for name := range g.decls {
		names = append(names, name)
	}
	slices.Sort(names)
	var b strings.Builder
	b.WriteString(header)
	for _, name := range names {
		b.WriteString("\n")
		b.WriteString(g.decls[name])
	}
	return b.String(), nil
}

func (g *generator) declare(t reflect.Type) error {
	name := t.Name()
	if name == "" {
		return fmt.Errorf("an unnamed struct cannot become an interface: %v", t)
	}
	if !identifier.MatchString(name) {
		return fmt.Errorf("%s cannot become an interface name", name)
	}
	if seen, ok := g.named[name]; ok {
		if seen != t {
			return fmt.Errorf("two types are named %s: %s and %s", name, seen.PkgPath(), t.PkgPath())
		}
		return nil
	}
	g.named[name] = t
	g.queue = append(g.queue, t)
	return nil
}

func (g *generator) declaration(t reflect.Type) (string, error) {
	fields := collect(t, nil, map[reflect.Type]bool{})
	if len(fields) == 0 {
		return "export type " + t.Name() + " = Record<string, never>;\n", nil
	}
	var b strings.Builder
	b.WriteString("export interface " + t.Name() + " {\n")
	for _, f := range fields {
		expr, err := g.fieldType(f)
		if err != nil {
			return "", fmt.Errorf("%s.%s: %w", f.owner.Name(), f.goName, err)
		}
		name := f.name
		if !identifier.MatchString(name) {
			name = strconv.Quote(name)
		}
		if f.optional {
			name += "?"
		}
		b.WriteString("  " + name + ": " + expr + ";\n")
	}
	b.WriteString("}\n")
	return b.String(), nil
}

func (g *generator) fieldType(f field) (string, error) {
	if f.quoted {
		switch f.typ.Kind() {
		case reflect.Bool, reflect.String, reflect.Float32, reflect.Float64,
			reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
			reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr:
			return "string", nil
		}
	}
	expr, nullable, err := g.expr(f.typ)
	if err != nil {
		return "", err
	}
	if nullable && !f.optional {
		expr += " | null"
	}
	return expr, nil
}

func (g *generator) element(t reflect.Type) (string, error) {
	expr, nullable, err := g.expr(t)
	if err != nil {
		return "", err
	}
	if nullable {
		return "(" + expr + " | null)", nil
	}
	return expr, nil
}

func (g *generator) expr(t reflect.Type) (string, bool, error) {
	switch {
	case t == timeType:
		return "string", false, nil
	case t == rawMessageType:
		return "unknown", false, nil
	case t.Kind() == reflect.Interface:
		return "unknown", false, nil
	case t.Kind() == reflect.Pointer:
		expr, _, err := g.expr(t.Elem())
		return expr, true, err
	case t.Implements(jsonMarshalerType) || reflect.PointerTo(t).Implements(jsonMarshalerType):
		return "", false, fmt.Errorf("%v writes its own JSON, which the generator cannot see", t)
	case t.Implements(textMarshalerType) || reflect.PointerTo(t).Implements(textMarshalerType):
		return "", false, fmt.Errorf("%v writes its own text, which the generator cannot see", t)
	}
	switch t.Kind() {
	case reflect.Bool:
		return "boolean", false, nil
	case reflect.String:
		return "string", false, nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr,
		reflect.Float32, reflect.Float64:
		return "number", false, nil
	case reflect.Slice, reflect.Array:
		if t.Kind() == reflect.Slice && t.Elem().Kind() == reflect.Uint8 {
			return "string", false, nil
		}
		elem, err := g.element(t.Elem())
		return elem + "[]", false, err
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return "", false, fmt.Errorf("a map with %v keys cannot become a Record", t.Key())
		}
		value, nullable, err := g.expr(t.Elem())
		if nullable {
			value += " | null"
		}
		return "Record<string, " + value + ">", false, err
	case reflect.Struct:
		return t.Name(), false, g.declare(t)
	}
	return "", false, fmt.Errorf("a %v cannot be sent as JSON", t.Kind())
}

func collect(t reflect.Type, index []int, visiting map[reflect.Type]bool) []field {
	if visiting[t] {
		return nil
	}
	visiting[t] = true
	defer delete(visiting, t)
	var all []field
	for i := range t.NumField() {
		f := t.Field(i)
		tag := f.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		path := append(slices.Clone(index), i)
		if f.Anonymous {
			ft := f.Type
			if ft.Kind() == reflect.Pointer {
				ft = ft.Elem()
			}
			if !f.IsExported() && ft.Kind() != reflect.Struct {
				continue
			}
			if name == "" && ft.Kind() == reflect.Struct {
				all = append(all, collect(ft, path, visiting)...)
				continue
			}
		} else if !f.IsExported() {
			continue
		}
		options := strings.Split(opts, ",")
		all = append(all, field{
			name:     cmp.Or(name, f.Name),
			index:    path,
			tagged:   name != "",
			typ:      f.Type,
			owner:    t,
			goName:   f.Name,
			optional: slices.Contains(options, "omitempty") || slices.Contains(options, "omitzero"),
			quoted:   slices.Contains(options, "string"),
		})
	}
	if len(index) > 0 {
		return all
	}
	return dominant(all)
}

func dominant(all []field) []field {
	byName := map[string][]field{}
	for _, f := range all {
		byName[f.name] = append(byName[f.name], f)
	}
	var out []field
	for _, group := range byName {
		depth := len(group[0].index)
		for _, f := range group {
			depth = min(depth, len(f.index))
		}
		var shallow, tagged []field
		for _, f := range group {
			if len(f.index) == depth {
				shallow = append(shallow, f)
				if f.tagged {
					tagged = append(tagged, f)
				}
			}
		}
		switch {
		case len(shallow) == 1:
			out = append(out, shallow[0])
		case len(tagged) == 1:
			out = append(out, tagged[0])
		}
	}
	slices.SortFunc(out, func(a, b field) int { return slices.Compare(a.index, b.index) })
	return out
}
